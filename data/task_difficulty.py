def infer_difficulty(task_id: str, based_on: str | None = None) -> str:
    """Уровень сложности задачи по её содержанию."""
    source = based_on or task_id or ""
    if source in _HARD:
        return DIFFICULTY_HARD
    if source in _EASY:
        return DIFFICULTY_EASY
    return DIFFICULTY_MEDIUM


_DIFFICULTY_RANK = {
    DIFFICULTY_EASY: 0,
    DIFFICULTY_MEDIUM: 1,
    DIFFICULTY_HARD: 2,
}


def sort_tasks_by_difficulty(tasks: list[dict]) -> list[dict]:
    """Стабильная сортировка: лёгкие → средние → сложные.

    Задачи одного уровня сохраняют прежний порядок, поэтому пара
    «исправь» и похожая обычная задача остаётся рядом.
    """
    return sorted(
        tasks,
        key=lambda task: _DIFFICULTY_RANK.get(task.get("difficulty"), 1),
    )
